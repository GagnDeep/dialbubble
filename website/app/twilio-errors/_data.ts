export function getTwilioError(code: string): TwilioError | undefined {
  return twilioErrors.find((error) => error.code === code);
}

export function errorPath(code: string): string {
  return `/twilio-errors/${code}`;
}

export function errorTitle(error: TwilioError): string {
  const label = error.severity === "Warning" ? "warning" : "error";
  return `Twilio ${label} ${error.code}: ${error.short}`;
}

/** Removes the [label](url) and `code` markup, for JSON-LD and other plain text. */
export function stripMarkup(text: string): string {
  return text.replace(/\[([^\]]+)\]\([^)]+\)/g, "$1").replace(/`([^`]+)`/g, "$1");
}
