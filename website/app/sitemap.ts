import fs from "node:fs";
import path from "node:path";
import type { MetadataRoute } from "next";

export const dynamic = "force-static";
import { indexablePages } from "@/lib/registry";
import { absoluteUrl } from "@/lib/seo";

export default function sitemap(): MetadataRoute.Sitemap {
  return indexablePages().map((entry) => {
    // A registered page with no page.tsx would put a 404 in the sitemap. Warn in the build log.
    const isErrorPage = entry.path.startsWith("/twilio-errors/"); // Generated by /twilio-errors/[code].
    if (!isErrorPage && !fs.existsSync(path.join(process.cwd(), "app", entry.path, "page.tsx"))) {
      console.warn(`[sitemap] ${entry.path} is in the registry but has no page.tsx`);
    }
    const lastModified = entry.updated ?? entry.published;
    return { url: absoluteUrl(entry.path), ...(lastModified ? { lastModified } : {}) };
  });
}
